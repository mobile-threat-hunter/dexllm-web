#!/usr/bin/env python3
"""Regenerate vendor/gen/android_api_data.h from dexllm's android_api_map.json.

Usage: python3 gen_android_api_data.py <path-to-android_api_map.json>

The header is emitted in JSON insertion order — the same order
dexllm.capability.summarize_capabilities iterates — so api_hits and the
aggregation stay byte-identical to the Python report on the same input.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "vendor" / "gen" / "android_api_data.h"


def cstr(s: str) -> str:
    return json.dumps(s)  # valid C string literal for the ASCII-only catalog


def clist(items) -> str:
    return "{" + ", ".join(cstr(i) for i in items) + "}"


def main() -> None:
    src = Path(sys.argv[1])
    catalog = json.loads(src.read_text())
    version = catalog["version"]
    entries = catalog["entries"]

    rows = []
    for sig, meta in entries.items():
        rows.append(
            "        {%s, %s, %s, %s},"
            % (
                cstr(sig),
                clist(meta.get("permissions", [])),
                clist(meta.get("categories", [])),
                clist(meta.get("flags", [])),
            )
        )

    OUT.write_text(
        f"""// GENERATED by gen_android_api_data.py — DO NOT EDIT.
// Source: dexllm src/dexllm/data/android_api_map.json (catalog {version}).
// Emitted in JSON insertion order (== capability.summarize_capabilities'
// iteration order) so api_hits + aggregation are byte-identical.
#pragma once

#include <string>
#include <string_view>
#include <vector>

namespace dexkit::ext::gen {{

struct CapabilityCatalogEntry {{
    // METHOD descriptor (Lcls;->name(proto)ret) or, since dexllm#36, a FIELD
    // descriptor (Lcls;->NAME:Ltype;) — the key's shape selects the lookup.
    std::string api_signature;
    std::vector<std::string> permissions;  // catalog order (may be empty)
    std::vector<std::string> categories;   // catalog order
    std::vector<std::string> flags;        // orthogonal axis (e.g. IDENTIFIER)
}};

inline constexpr std::string_view kCapabilityCatalogVersion = "{version}";

inline const std::vector<CapabilityCatalogEntry>& CapabilityCatalog() {{
    static const std::vector<CapabilityCatalogEntry> kC = {{
{chr(10).join(rows)}
    }};
    return kC;
}}

}}  // namespace dexkit::ext::gen
"""
    )
    print(f"wrote {OUT} — catalog {version}, {len(entries)} entries")


if __name__ == "__main__":
    main()
